// Translate application messages at the display boundary; stored records and API contracts stay unchanged.
export function translateDiagnostic(source: string): string | undefined {
  const prefixes: Record<string, string> = {
    '危険なファイル名: ': 'Unsafe filename: ', 'ファイルが大きすぎます: ': 'File too large: ',
    '入力ファイルが大きすぎます: ': 'Input file too large: ', 'ZIP内の危険なパス: ': 'Unsafe ZIP path: ',
    'ZIP内のファイルが大きすぎます: ': 'File in ZIP is too large: ', 'ZIPの圧縮率が異常です: ': 'Unusual ZIP compression ratio: ',
  };
  for (const [prefix, english] of Object.entries(prefixes)) if (source.startsWith(prefix)) return english + source.slice(prefix.length);
  const suffixes: Record<string, string> = {
    ': current_node がないため最後の枝を採用しました': ': Used the last branch because current_node is missing.',
    ': JSONLが不正です': ': Invalid JSONL.', ': JSONが不正です': ': Invalid JSON.', ': frontmatterが不正です': ': Invalid frontmatter.',
  };
  for (const [suffix, english] of Object.entries(suffixes)) if (source.endsWith(suffix)) return source.slice(0, -suffix.length) + english;
  return undefined;
}

